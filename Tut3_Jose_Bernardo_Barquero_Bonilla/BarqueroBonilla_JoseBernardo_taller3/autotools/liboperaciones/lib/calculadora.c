#include <calculadora.h>

#include <math.h>

float op_suma ( float a, float b )
{
	return a + b;
}

float op_resta ( float a, float b )
{
	return a - b;
}

float op_mult ( float a, float b )
{
	return a * b;
}

float op_div ( float a, float b )
{
	return a / b;
}

float op_sqrt ( float a )
{
	return sqrtf ( a ) ;
}